import { Blueprint, SaveComponent, SaveEntity } from "@etothepii/satisfactory-file-parser";
import { Transform, Vec3, add, length, multiply, rotate, scale, snap, sub, toLocal, toWorld, transform, vec, yaw } from "./geometry.js";
import { SELF, TemplateLibrary, cloneDeep } from "./templates.js";
import { costOf } from "./data/costs.js";

/** A placed building inside a blueprint under construction. */
export interface Placed {
  entity: SaveEntity;
  components: Map<string, SaveComponent>;
}

/** Reference to one connector of a placed building, e.g. { building, name: "Input0" }. */
export interface ConnectorRef {
  building: Placed;
  name: string;
}

/**
 * One end of a belt: a connector it attaches to, or just a position. A belt end left unattached is
 * an "open connection" that the game's blueprint Auto-Connect mode links to nearby belts (up to 16 m).
 */
export type BeltEnd = (ConnectorRef | { building?: undefined; name?: undefined }) & { position: Vec3 };

const LEVEL = "Persistent_Level";

/** Appended to every generated blueprint's description so tools can tell them apart from hand-made ones. */
export const GENERATED_MARKER = "Generated by satisfactory-blueprints.";

function objectRef(pathName: string) {
  return { levelName: LEVEL, pathName };
}

/** Builds a blueprint by instantiating building templates and wiring them together. */
export class BlueprintBuilder {
  private readonly library: TemplateLibrary;
  private readonly objects: (SaveEntity | SaveComponent)[] = [];
  private readonly costs = new Map<string, number>();
  private readonly recipes = new Set<string>();
  // Arbitrary unique ids in the range the game itself uses for instance names.
  private nextId = 2147000000;

  /** All templates must come from one save version; use selectLibrary() to pick it. */
  constructor(library: TemplateLibrary) {
    this.library = library;
  }

  /**
   * Coordinates passed to every method are relative to the current frame (identity by default).
   * Generators build a piece (e.g. one factory floor) in its own convenient coordinates and let the
   * frame place and orient it in the blueprint.
   */
  private frame: Transform = transform(vec());

  withFrame<T>(frame: Transform, build: () => T): T {
    const previous = this.frame;
    this.frame = frame;
    try {
      return build();
    } finally {
      this.frame = previous;
    }
  }

  /** Converts a frame-relative point to blueprint coordinates. */
  toBlueprint(point: Vec3): Vec3 {
    return toWorld(this.frame, point);
  }

  private toBlueprintDirection(direction: Vec3): Vec3 {
    return rotate(this.frame.rotation, direction);
  }

  /** Places a building of the given type (full typePath or a unique suffix such as "Build_ConstructorMk1_C"). */
  place(type: string, at: Transform): Placed {
    const placed = this.instantiate(type, {
      rotation: multiply(this.frame.rotation, at.rotation),
      translation: this.toBlueprint(at.translation),
      scale3d: at.scale3d,
    });
    this.addCost(costOf(placed.entity.typePath));
    return placed;
  }

  /** Creates the objects of a building at a transform in blueprint coordinates. */
  private instantiate(type: string, at: Transform): Placed {
    const typePath = this.resolveType(type);
    const template = this.library.types[typePath];
    const selfName = `${LEVEL}:PersistentLevel.${typePath.split(".").pop()}_${this.nextId++}`;

    const entity = this.renameDeep(cloneDeep(template.entity), selfName);
    entity.transform = { ...at } as any;

    const components = new Map<string, SaveComponent>();
    for (const component of template.components) {
      const copy = this.renameDeep(cloneDeep(component), selfName);
      components.set(copy.instanceName.split(".").pop()!, copy);
    }

    this.objects.push(entity, ...components.values());
    const built = (entity.properties as any).mBuiltWithRecipe?.value?.pathName;
    if (built) this.recipes.add(built);
    return { entity, components };
  }

  /** Sets the production recipe of a machine. */
  setRecipe(machine: Placed, recipePath: string): void {
    (machine.entity.properties as any).mCurrentRecipe = {
      type: "ObjectProperty",
      name: "mCurrentRecipe",
      propertyTagType: { name: "ObjectProperty", children: [] },
      value: { levelName: "", pathName: recipePath },
    };
  }

  /** Sets a machine's clock speed as a fraction (1 = 100%). Values above 1 need Power Shards in-game. */
  setClock(machine: Placed, fraction: number): void {
    if (!(fraction > 0 && fraction <= 2.5)) throw new Error(`Clock speed must be between 0 and 250%, got ${fraction * 100}%.`);
    for (const name of ["mPendingPotential", "mCurrentPotential"]) {
      (machine.entity.properties as any)[name] = {
        type: "FloatProperty",
        name,
        propertyTagType: { name: "FloatProperty", children: [] },
        value: fraction,
      };
    }
  }

  /**
   * Places a conveyor belt from an output connector to an input connector. Without `direction` it is
   * straight; with it, the belt leaves and arrives moving in that direction, so a sideways or vertical
   * offset becomes a smooth S-curve (belts store such curves as two points with tangents).
   */
  belt(type: string, from: BeltEnd, to: BeltEnd, direction?: Vec3): Placed {
    const start = this.toBlueprint(from.position);
    const delta = sub(this.toBlueprint(to.position), start);
    const belt = this.instantiate(type, transform(start));
    // Straight belts saved by the game use tangents half as long as the belt.
    const tangent = direction ? scale(this.toBlueprintDirection(direction), length(delta)) : scale(delta, 0.5);
    (belt.entity.properties as any).mSplineData.values = [vec(), delta].map((location) => this.splinePoint(belt, location, tangent));
    if (from.building) this.link({ building: belt, name: "ConveyorAny0" }, from);
    if (to.building) this.link({ building: belt, name: "ConveyorAny1" }, to);
    // Belts cost about one part per 2 m of length.
    const meters = length(delta) / 100;
    this.addCost(Object.fromEntries(Object.entries(costOf(belt.entity.typePath)).map(([item, n]) => [item, n * Math.max(1, Math.ceil(meters / 2))])));
    return belt;
  }

  /** A lift that carries items straight down by `height` cm, continuing in direction `travelYaw`. */
  liftDown(type: string, top: Vec3, height: number, travelYaw: number): { lift: Placed; input: Vec3; output: Vec3 } {
    return this.lift(type, top, -height, travelYaw, travelYaw);
  }

  /**
   * Places a conveyor lift. Items enter at `start` moving in direction `inYaw` (degrees, 0 = +X),
   * travel `rise` cm up (negative = down) and leave moving in direction `outYaw`.
   *
   * Learned from real blueprints: the lift's transform sits at its input end, `mTopTransform` holds
   * the other end relative to it, and both belt connectors lie on the lift's vertical axis. The input
   * accepts items moving along the lift's local -X axis; an unrotated far end sends them back out
   * along +X (a U-turn), and rotating the far end by R turns the exit by R.
   */
  lift(type: string, start: Vec3, rise: number, inYaw: number, outYaw: number): { lift: Placed; input: Vec3; output: Vec3 } {
    const lift = this.place(type, transform(start, inYaw + 180));
    // q and -q are the same rotation; keep the form the game writes (z >= 0 for a half turn).
    const raw = yaw(outYaw - inYaw - 180);
    const turn = raw.w < -1e-9 || (Math.abs(raw.w) <= 1e-9 && raw.z < 0) ? { ...raw, z: -raw.z, w: -raw.w } : raw;
    const props = lift.entity.properties as any;
    delete props.mIsReversed;
    const struct = (name: string, structType: string, value: unknown) => ({
      type: "StructProperty",
      name,
      propertyTagType: { name: "StructProperty", children: [{ name: structType, children: [] }] },
      value,
    });
    props.mTopTransform = struct("mTopTransform", "Transform", {
      type: "Transform",
      properties: {
        Rotation: struct("Rotation", "Quat", { x: 0, y: 0, z: snap(turn.z, 1e-9), w: snap(turn.w, 1e-9) }),
        Translation: struct("Translation", "Vector", { x: 0, y: 0, z: rise }),
      },
    });
    return { lift, input: start, output: vec(start.x, start.y, start.z + rise) };
  }

  /**
   * Places a quarter-circle belt: it starts at `from` moving along `fromDir` and ends `radius` cm
   * further along both directions, moving along `toDir` (perpendicular). Returns its free end.
   */
  beltTurn(type: string, from: BeltEnd, fromDir: Vec3, toDir: Vec3, radius: number): BeltEnd & { building: Placed; name: string } {
    const end = add(from.position, add(scale(fromDir, radius), scale(toDir, radius)));
    const start = this.toBlueprint(from.position);
    const belt = this.instantiate(type, transform(start));
    // Hermite tangents of length 1.657 r approximate a circular quarter arc.
    const k = 1.657 * radius;
    (belt.entity.properties as any).mSplineData.values = [
      this.splinePoint(belt, vec(), scale(this.toBlueprintDirection(fromDir), k)),
      this.splinePoint(belt, sub(this.toBlueprint(end), start), scale(this.toBlueprintDirection(toDir), k)),
    ];
    if (from.building) this.link({ building: belt, name: "ConveyorAny0" }, from);
    this.addCost(Object.fromEntries(Object.entries(costOf(belt.entity.typePath)).map(([item, n]) => [item, n * Math.max(1, Math.ceil((Math.PI * radius) / 400))])));
    return { building: belt, name: "ConveyorAny1", position: end };
  }

  /**
   * Places a pipeline between two points. Pipes leave and enter horizontally (`direction` at both
   * ends), so a height difference becomes a smooth S-curve. Like the game, the spline gets a point
   * about every meter. Either end may be left open (a port for Auto-Connect).
   */
  pipe(type: string, from: BeltEnd, to: BeltEnd, direction: Vec3): Placed {
    const start = this.toBlueprint(from.position);
    const pipe = this.instantiate(type, transform(start));
    const delta = sub(this.toBlueprint(to.position), start);
    const horizontal = Math.hypot(delta.x, delta.y);
    const t0 = scale(this.toBlueprintDirection(direction), Math.max(horizontal, 100));
    const segments = Math.max(1, Math.ceil(length(delta) / 100));
    // Cubic Hermite from the origin to `delta`, with tangent t0 at both ends (the start point is 0).
    const combine = (a: number, b: number) => add(scale(t0, a), scale(delta, b));
    const at = (s: number) => combine(s ** 3 - 2 * s ** 2 + s + (s ** 3 - s ** 2), -2 * s ** 3 + 3 * s ** 2);
    const slope = (s: number) => combine(3 * s ** 2 - 4 * s + 1 + (3 * s ** 2 - 2 * s), -6 * s ** 2 + 6 * s);
    (pipe.entity.properties as any).mSplineData.values = Array.from({ length: segments + 1 }, (_, i) => {
      const s = i / segments;
      return this.splinePoint(pipe, at(s), scale(slope(s), 1 / segments));
    });
    if (from.building) this.link({ building: pipe, name: "PipelineConnection0" }, from);
    if (to.building) this.link({ building: pipe, name: "PipelineConnection1" }, to);
    return pipe;
  }

  /** Connects two belt connectors to each other (both sides store the link). */
  link(a: ConnectorRef, b: ConnectorRef): void {
    const ca = this.component(a);
    const cb = this.component(b);
    (ca.properties as any).mConnectedComponent = this.objectProperty("mConnectedComponent", cb.instanceName);
    (cb.properties as any).mConnectedComponent = this.objectProperty("mConnectedComponent", ca.instanceName);
  }

  /** Runs a power line between two power connectors, e.g. a pole's "PowerConnection" and a machine's "PowerInput". */
  wire(a: ConnectorRef & { position: Vec3 }, b: ConnectorRef & { position: Vec3 }): Placed {
    const line = this.place("Build_PowerLine_C", transform(a.position));
    const ca = this.component(a);
    const cb = this.component(b);
    const special = line.entity.specialProperties as any;
    special.source = objectRef(ca.instanceName);
    special.target = objectRef(cb.instanceName);

    const props = line.entity.properties as any;
    const wire = props.mWireInstances?.values?.[0]?.properties;
    if (wire?.Locations) {
      wire.Locations[0].value = this.toBlueprint(a.position);
      wire.Locations[1].value = this.toBlueprint(b.position);
    }
    if (props.mCachedLength) props.mCachedLength.value = length(sub(b.position, a.position));

    for (const c of [ca, cb]) {
      const wires = (c.properties as any).mWires;
      if (wires) wires.values.push(objectRef(line.entity.instanceName));
    }
    return line;
  }

  /** Name of a building's power connector; it varies by building ("PowerInput", "PowerConnection", ...). */
  powerConnector(building: Placed): string {
    const found = [...building.components].find(([, c]) => c.typePath.endsWith("FGPowerConnectionComponent"));
    if (!found) throw new Error(`${building.entity.typePath} has no power connector.`);
    return found[0];
  }

  /** Position of a building-local point, in the current frame's coordinates. */
  worldPoint(building: Placed, local: Vec3): Vec3 {
    return toLocal(this.frame, toWorld(building.entity.transform as any, local));
  }

  /**
   * @param options.yaw Rotates the whole layout around the blueprint center (degrees). Generators lay
   *   things out in whatever frame is convenient and rotate at the end so the blueprint's front
   *   (the white arrow shown while placing it, which points to -Y) faces the right way.
   */
  build(name: string, options: { description?: string; designerSize?: number; yaw?: number } = {}): Blueprint {
    if (options.yaw) this.rotateLayout(options.yaw);
    const header = cloneDeep(this.library.header);
    const size = options.designerSize ?? this.requiredDesignerSize();
    header.designerDimension = { x: size, y: size, z: size };
    header.recipeReferences = [...this.recipes].sort().map((pathName) => ({ levelName: "", pathName }));
    header.itemCosts = [...this.costs].map(([pathName, amount]) => [{ levelName: "", pathName }, Math.ceil(amount)]);

    return {
      name,
      compressionInfo: cloneDeep(this.library.compressionInfo),
      header,
      config: {
        configVersion: 3,
        description: [options.description, GENERATED_MARKER].filter(Boolean).join(" "),
        color: { r: 0.9, g: 0.45, b: 0.1, a: 1 },
        iconID: -1,
        referencedIconLibrary: "",
        iconLibraryType: "",
      },
      objects: this.objects,
    };
  }

  /**
   * Smallest Blueprint Designer (in foundations per side, at least the 4 x 4 Mk1) that holds every
   * building. The designer is centered on the origin; 4 m of margin covers building footprints.
   */
  requiredDesignerSize(): number {
    let extent = 0;
    for (const obj of this.objects) {
      const t = (obj as SaveEntity).transform?.translation;
      if (t) extent = Math.max(extent, Math.abs(t.x), Math.abs(t.y));
    }
    return Math.max(4, Math.ceil((2 * (extent + 400)) / 800));
  }

  /** Rotates every placed object around the vertical axis through the origin. */
  private rotateLayout(degrees: number): void {
    const q = yaw(degrees);
    const turn = (v: Vec3): Vec3 => {
      const r = rotate(q, v);
      // Remove float noise so grid-aligned layouts stay grid-aligned.
      return vec(snap(r.x, 0.001), snap(r.y, 0.001), snap(r.z, 0.001));
    };
    for (const obj of this.objects) {
      const t = (obj as SaveEntity).transform as Transform | undefined;
      if (!t?.translation) continue;
      t.translation = turn(t.translation);
      t.rotation = multiply(q, t.rotation);
      // Power lines also store their end points in blueprint space.
      for (const location of (obj.properties as any).mWireInstances?.values?.[0]?.properties?.Locations ?? []) {
        location.value = turn(location.value);
      }
    }
  }

  private resolveType(type: string): string {
    if (this.library.types[type]) return type;
    const matches = Object.keys(this.library.types).filter((t) => t.endsWith(`.${type}`));
    if (matches.length !== 1) throw new Error(`Unknown building type "${type}". Add a blueprint that contains it and run "sbp learn".`);
    return matches[0];
  }

  private component(ref: ConnectorRef): SaveComponent {
    const wanted = ref.name.toLowerCase();
    const found = [...ref.building.components].find(([name]) => name.toLowerCase() === wanted);
    if (!found) throw new Error(`${ref.building.entity.typePath} has no connector "${ref.name}"`);
    return found[1];
  }

  private objectProperty(name: string, pathName: string) {
    return { type: "ObjectProperty", name, propertyTagType: { name: "ObjectProperty", children: [] }, value: objectRef(pathName) };
  }

  private splinePoint(belt: Placed, location: Vec3, tangent: Vec3) {
    const template = (belt.entity.properties as any).mSplineData.values[0];
    const point = cloneDeep(template);
    point.properties.Location.value = { ...location };
    point.properties.ArriveTangent.value = { ...tangent };
    point.properties.LeaveTangent.value = { ...tangent };
    return point;
  }

  private renameDeep<T>(value: T, selfName: string): T {
    if (typeof value === "string") return (value.includes(SELF) ? value.split(SELF).join(selfName) : value) as T;
    if (Array.isArray(value)) return value.map((v) => this.renameDeep(v, selfName)) as T;
    if (value && typeof value === "object") {
      for (const key of Object.keys(value)) (value as any)[key] = this.renameDeep((value as any)[key], selfName);
    }
    return value;
  }

  private addCost(cost: Record<string, number>): void {
    for (const [item, amount] of Object.entries(cost)) this.costs.set(item, (this.costs.get(item) ?? 0) + amount);
  }
}
